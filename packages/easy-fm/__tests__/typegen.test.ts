import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import * as ts from 'typescript';
import { z } from 'zod';
import {
    generate,
    zodTypegenValidator,
} from '../dist/typegen/index.js';

describe('typegen', () => {
    it('keeps configurations generated by earlier v5 betas loadable', async () => {
        const root = await mkdtemp(join(tmpdir(), 'easyfm-typegen-compat-'));
        try {
            expect(zodTypegenValidator()).toEqual({ kind: 'zod' });
            await expect(
                generate({
                    output: join(root, 'generated'),
                    validator: zodTypegenValidator(),
                    source: {
                        async introspect() {
                            return { version: 1, layouts: [] };
                        },
                    },
                }),
            ).resolves.toMatchObject({ layouts: 0, databases: 1 });
        } finally {
            await rm(root, { recursive: true, force: true });
        }
    });

    it('generates provider-neutral Zod client and narrows immutable fields', async () => {
        const root = await mkdtemp(join(tmpdir(), 'easyfm-typegen-'));
        const output = join(root, 'generated');
        try {
            await generate({
                output,
                source: {
                    async introspect() {
                        return {
                            version: 1 as const,
                            layouts: [
                                {
                                    name: 'API People',
                                    clientName: 'people',
                                    fields: [
                                        {
                                            name: 'Name',
                                            result: 'text',
                                            type: 'normal',
                                            writable: true,
                                            required: true,
                                        },
                                        {
                                            name: 'Display Name',
                                            result: 'text',
                                            type: 'calculation',
                                            writable: false,
                                            required: false,
                                        },
                                    ],
                                    portals: {},
                                },
                            ],
                        };
                    },
                },
            });
            const runtime = await readFile(join(output, 'client.js'), 'utf8');
            const client = await readFile(join(output, 'client.d.ts'), 'utf8');
            const manifest = await readFile(join(output, 'schema.json'), 'utf8');
            expect(client).toContain('"Display Name": ReadonlyField<TextField<');
            expect(client).toContain('export interface EasyFMProviders');
            expect(client).toContain('database: DatabaseProvider');
            expect(client).toContain('export interface EasyFMClient');
            expect(client).toContain('database: DatabaseClient');
            expect(client).toContain('people: Layout<DatabasePeopleLayout<');
            expect(client).toContain('export interface DatabasePeopleFields');
            expect(client).toContain('fields: DatabasePeopleFields');
            expect(client).toContain(
                'createEasyFMClient<const SchemaOverrides extends EasyFMSchemaOverrides',
            );
            expect(runtime).toContain(
                'withSchemaValidation(provider, createDatabaseSchemas(schemaOverrides))',
            );
            expect(runtime).toContain('providerRecord: z.object(');
            expect(runtime).toContain('Generated by easyfm typegen');
            expect(runtime).toContain('metadata: {fields:');
            expect(runtime).toContain('schemaOverrides.database');
            expect(runtime).not.toContain('DataApiProvider');
            expect(runtime).not.toContain('export interface');
            expect(JSON.parse(manifest).databases.database.transports).toEqual([
                'data-api',
                'odata',
            ]);
        } finally {
            await rm(root, { recursive: true, force: true });
        }
    });

    it('generates typed Zod field overrides', async () => {
        const root = await mkdtemp(join(tmpdir(), 'easyfm-typegen-plugin-'));
        try {
            await generate({
                output: join(root, 'generated'),
                source: {
                    async introspect() {
                        return {
                            version: 1,
                            layouts: [
                                {
                                    name: 'Flags',
                                    fields: [
                                        {
                                            name: 'Enabled',
                                            result: 'number',
                                            type: 'normal',
                                            writable: true,
                                            required: true,
                                        },
                                    ],
                                    portals: {},
                                },
                            ],
                        };
                    },
                },
            });
            const runtime = await readFile(join(root, 'generated', 'client.js'), 'utf8');
            const declarations = await readFile(
                join(root, 'generated', 'client.d.ts'),
                'utf8',
            );
            expect(runtime).toContain(
                'emptyFileMakerValueToNull((overrides?.["Flags"]?.fields?.["Enabled"] ?? z.number()))',
            );
            expect(declarations).toContain(
                '"Enabled"?: z.ZodType<number | null, number | null>',
            );
            expect(declarations).toContain(
                'NumberField<(ZodInput<NonNullable<SchemaOverrides["fields"]>["Enabled"], number> & number) | null>',
            );
        } finally {
            await rm(root, { recursive: true, force: true });
        }
    });

    it('infers a narrowed NumberField from a generated Zod override', async () => {
        const root = await mkdtemp(join(process.cwd(), '.easyfm-typegen-types-'));
        const output = join(root, 'generated');
        const consumer = join(root, 'consumer.ts');
        try {
            await generate({
                output,
                source: {
                    async introspect() {
                        return {
                            version: 1,
                            layouts: [
                                {
                                    name: 'Flags',
                                    fields: [
                                        {
                                            name: 'Enabled',
                                            result: 'number',
                                            type: 'normal',
                                            writable: true,
                                            required: true,
                                        },
                                        {
                                            name: 'Label',
                                            result: 'text',
                                            type: 'normal',
                                            writable: true,
                                            required: false,
                                        },
                                        {
                                            name: 'DueDate',
                                            result: 'date',
                                            type: 'normal',
                                            writable: true,
                                            required: false,
                                        },
                                        {
                                            name: 'DueTime',
                                            result: 'time',
                                            type: 'normal',
                                            writable: true,
                                            required: false,
                                        },
                                        {
                                            name: 'ChangedAt',
                                            result: 'timeStamp',
                                            type: 'normal',
                                            writable: true,
                                            required: false,
                                        },
                                        {
                                            name: 'Attachment',
                                            result: 'container',
                                            type: 'normal',
                                            writable: true,
                                            required: false,
                                        },
                                    ],
                                    portals: {},
                                },
                            ],
                        };
                    },
                },
            });
            await writeFile(
                consumer,
                `import {z} from 'zod'
import type {Layout} from '@jd-data-limited/easy-fm'
import {createEasyFMClient, type EasyFMProviders} from './generated/client.js'

declare const providers: EasyFMProviders
const client = createEasyFMClient(providers, {database: {Flags: {fields: {
    Enabled: z.union([z.literal(0), z.literal(1)])
}}}})
type Enabled = typeof client.database.Flags extends Layout<infer Definition>
    ? Definition['fields']['Enabled']['value']
    : never
declare const enabled: Enabled
const exact: 0 | 1 | null = enabled
void exact
`,
                'utf8',
            );
            const program = ts.createProgram([consumer], {
                target: ts.ScriptTarget.ES2022,
                module: ts.ModuleKind.NodeNext,
                moduleResolution: ts.ModuleResolutionKind.NodeNext,
                strict: true,
                skipLibCheck: true,
                noEmit: true,
            });
            const diagnostics = ts.getPreEmitDiagnostics(program);
            expect(
                ts.formatDiagnosticsWithColorAndContext(diagnostics, {
                    getCanonicalFileName: (name) => name,
                    getCurrentDirectory: () => process.cwd(),
                    getNewLine: () => '\n',
                }),
            ).toBe('');

            const generated = await import(
                pathToFileURL(join(output, 'client.js')).href
            );
            const metadataField = (
                name: string,
                result:
                    | 'number'
                    | 'text'
                    | 'date'
                    | 'time'
                    | 'timeStamp'
                    | 'container',
            ) => ({
                name,
                result,
                type: 'normal',
                displayType: 'editText',
                global: false,
                autoEnter: false,
                fourDigitYear: false,
                maxRepeat: 1,
                maxCharacters: 0,
                notEmpty: false,
                numeric: result === 'number',
                timeOfDay: false,
                repetitionStart: 1,
                repetitionEnd: 1,
            });
            const formatting = {
                dateFormat: 'MM/DD/YYYY',
                timeFormat: 'HH:mm:ss',
                timeStampFormat: 'MM/DD/YYYY HH:mm:ss',
            };
            const provider = {
                formatting,
                async connect() {
                    return {
                        formatting,
                        maxSessions: 1,
                        async openSession() {
                            return {
                                async execute(operation: { type: string }) {
                                    if (operation.type === 'layout.metadata') {
                                        return {
                                            fieldMetaData: [
                                                metadataField('Enabled', 'number'),
                                                metadataField('Label', 'text'),
                                                metadataField('DueDate', 'date'),
                                                metadataField('DueTime', 'time'),
                                                metadataField('ChangedAt', 'timeStamp'),
                                                metadataField('Attachment', 'container'),
                                            ],
                                            portalMetaData: {},
                                        };
                                    }
                                    return {
                                        recordId: '1',
                                        modId: '0',
                                        fieldData: {
                                            Enabled: '',
                                            Label: '',
                                            DueDate: '',
                                            DueTime: '',
                                            ChangedAt: '',
                                            Attachment: '',
                                        },
                                        portalData: {},
                                    };
                                },
                                async fetchContainer() {
                                    return new Response();
                                },
                                async close() {},
                            };
                        },
                    };
                },
            };
            const client = generated.createEasyFMClient(
                { database: provider },
                {
                    database: {
                        Flags: {
                            fields: {
                                Enabled: z.union([z.literal(0), z.literal(1)]),
                            },
                        },
                    },
                },
            );
            const record = await client.database.Flags.records.get(1);
            expect(record.fields.Enabled.value).toBeNull();
            expect(record.fields.Label.value).toBe('');
            expect(record.fields.DueDate.value).toBeNull();
            expect(record.fields.DueTime.value).toBeNull();
            expect(record.fields.ChangedAt.value).toBeNull();
            expect(record.fields.Attachment.value).toBeNull();
        } finally {
            await rm(root, { recursive: true, force: true });
        }
    });

    it('namespaces layouts and providers for multiple databases', async () => {
        const root = await mkdtemp(join(tmpdir(), 'easyfm-multi-db-'));
        const source = (name: string) => ({
            async introspect() {
                return {
                    version: 1 as const,
                    layouts: [{ name, fields: [], portals: {} }],
                };
            },
        });
        try {
            await generate({
                output: join(root, 'generated'),
                databases: {
                    crm: {
                        source: source('People'),
                        provider: 'data-api/odata',
                        transports: ['data-api', 'odata'],
                    },
                    stock: {
                        source: source('People'),
                        provider: 'custom',
                        transports: ['odata'],
                    },
                },
            });
            const runtime = await readFile(join(root, 'generated', 'client.js'), 'utf8');
            const client = await readFile(join(root, 'generated', 'client.d.ts'), 'utf8');
            const manifest = JSON.parse(
                await readFile(join(root, 'generated', 'schema.json'), 'utf8'),
            );
            expect(client).toContain('crm: DatabaseProvider');
            expect(client).toContain('stock: DatabaseProvider');
            expect(runtime).toContain(
                'crm: createCrmClient(providers.crm, schemaOverrides.crm)',
            );
            expect(runtime).toContain(
                'stock: createStockClient(providers.stock, schemaOverrides.stock)',
            );
            expect(manifest.databases.stock).toMatchObject({
                provider: 'custom',
                transports: ['odata'],
            });
        } finally {
            await rm(root, { recursive: true, force: true });
        }
    });

    it('reports source warnings with database context', async () => {
        const root = await mkdtemp(join(tmpdir(), 'easyfm-warning-'));
        const warnings: Array<{ database: string; message: string }> = [];
        try {
            const result = await generate({
                output: join(root, 'generated'),
                onDiagnostic: (warning) => warnings.push(warning),
                databases: {
                    crm: {
                        source: {
                            async introspect() {
                                return {
                                    version: 1,
                                    layouts: [],
                                    diagnostics: [
                                        {
                                            level: 'warning',
                                            layout: 'People',
                                            message: 'Field "<No Access>" was excluded.',
                                        },
                                    ],
                                };
                            },
                        },
                    },
                },
            });
            expect(warnings).toEqual([
                {
                    level: 'warning',
                    database: 'crm',
                    layout: 'People',
                    message: 'Field "<No Access>" was excluded.',
                },
            ]);
            expect(result.diagnostics).toEqual(warnings);
        } finally {
            await rm(root, { recursive: true, force: true });
        }
    });

    it('creates a working user entrypoint once and never overwrites it', async () => {
        const root = await mkdtemp(join(tmpdir(), 'easyfm-entrypoint-'));
        const entrypoint = join(root, 'src', 'easyfm.ts');
        const config = {
            output: join(root, 'src', 'generated'),
            entrypoint,
            databases: {
                crm: {
                    source: {
                        async introspect() {
                            return { version: 1 as const, layouts: [] };
                        },
                    },
                    runtime: {
                        provider: 'data-api' as const,
                        hostnameEnv: 'FM_CRM_HOST',
                        databaseEnv: 'FM_CRM_DATABASE',
                        usernameEnv: 'FM_CRM_USERNAME',
                        passwordEnv: 'FM_CRM_PASSWORD',
                    },
                },
            },
        };
        try {
            const first = await generate(config);
            expect(first.entrypoint?.created).toBe(true);
            const contents = await readFile(entrypoint, 'utf8');
            expect(contents).toContain('export const easyfm = createEasyFMClient');
            expect(contents).toContain('required("FM_CRM_PASSWORD")');
            const second = await generate(config);
            expect(second.entrypoint?.created).toBe(false);
            expect(await readFile(entrypoint, 'utf8')).toBe(contents);
        } finally {
            await rm(root, { recursive: true, force: true });
        }
    });
});
